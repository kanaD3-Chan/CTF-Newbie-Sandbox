# 方式二：逆向算法，模拟 key 演化过程

enc = [
    0xda, 0x43, 0x35, 0x30, 0x17, 0x9b, 0x7d, 0x69,
    0x28, 0xa2, 0x85, 0x94, 0x93, 0xfb, 0x57, 0xa5,
    0x09, 0x59, 0x22, 0xde, 0x42, 0x78, 0x9b, 0x56,
    0xaf, 0x50, 0x04, 0x07, 0xfb, 0xec, 0x56, 0x7a
]

seed = (0xabcd + 0xef) & 0xff
key = seed
flag = ''
for e in enc:
    flag += chr(e ^ key)
    key = (key * 7 + 11) & 0xff
print(flag)
