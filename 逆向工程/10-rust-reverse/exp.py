#!/usr/bin/env python3
# Rust binary: notice mangled symbols (e.g. _ZN...), LLVM-style strings
# Go binary: notice no-mangled-main, goroutine prologue, (ptr,len) string representation

rust_enc = [
    0xa5, 0xaf, 0xa2, 0xa4, 0xb8, 0xb1, 0xb6, 0xf6,
    0xb7, 0x9c, 0xb1, 0xf0, 0xb5, 0xf0, 0xb1, 0xb0,
    0xf0, 0x9c, 0xb4, 0xf2, 0xb7, 0xab, 0x9c, 0xa4,
    0xa7, 0xa1, 0x9c, 0xbe,
]
rust_flag = ''.join(chr(b ^ 0xc3) for b in rust_enc)
print("Rust flag:", rust_flag)

go_enc = [
    0x8d, 0x87, 0x8a, 0x8c, 0x90, 0x8c, 0xdb, 0xb4,
    0x99, 0xd8, 0x9d, 0xd8, 0x99, 0x98, 0xd8, 0xb4,
    0x8f, 0x9c, 0xdf, 0x99, 0x8d, 0x96,
]
go_flag = ''.join(chr(b ^ 0xeb) for b in go_enc)
print("Go flag: ", go_flag)
