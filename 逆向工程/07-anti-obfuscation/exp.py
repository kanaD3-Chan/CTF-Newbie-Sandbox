#!/usr/bin/env python3
# The key derivation looks complex but simplifies to a single XOR per byte
# Strip the dead code and opaque predicates, simplify the key expression

enc = [
    0x8f, 0x80, 0x66, 0x65, 0x0e, 0x6c, 0x10, 0x51,
    0x73, 0x72, 0x5a, 0x7f, 0x3e, 0x84, 0x3f, 0x57,
    0x49, 0x12, 0x08, 0x3f, 0xb1, 0xeb, 0x87, 0xbd,
    0xd3, 0xd9,
]

flag = ''
for i, e in enumerate(enc):
    k = i + 0xab
    k = (k * 7 + 11) & 0xff
    k ^= 0x55
    k = (k + 0x37) & 0xff
    k ^= 0xcd
    flag += chr(e ^ k)

print(flag)
