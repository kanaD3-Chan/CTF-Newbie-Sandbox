#!/usr/bin/env python3
"""RSA small n: factor n, compute d, decrypt."""
from Crypto.Util.number import long_to_bytes

n = 1986782301606895820729426007098712384204697189110999228921331090585016727924863499252636230723009
e = 65537
c = 531007718670362543784438428536264190382842690924390441104050349959817007247370159032984028611034

# These are known from factoring n (via factordb or similar)
p = 1368375491339831888364605239871197553189834443789
q = 1451927715879766866763544509174952941974446894981
assert p * q == n

phi = (p - 1) * (q - 1)
d = pow(e, -1, phi)
m = pow(c, d, n)
flag = long_to_bytes(m).decode()
print(f"Flag: {flag}")
